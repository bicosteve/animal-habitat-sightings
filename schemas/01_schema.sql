-- =============================================================================
-- 01_schema.sql
-- Animal Habitats and Sightings Management System
-- Target: Oracle Database 19c/21c/23c with Oracle Spatial available.
--
-- Design notes:
--   * ANIMALS is a supporting lookup/entity table required by the Animal_Name
--     foreign keys.
--   * Surrogate ANIMAL_ID keys avoid using mutable names as foreign keys;
--     ANIMAL_NAME is still UNIQUE for lookup and display.
--   * WGS 84 / EPSG:4326 is used for longitude/latitude geometries.
--   * Geometry metadata is registered BEFORE spatial indexes are created.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Supporting animal table
-- ---------------------------------------------------------------------------
CREATE TABLE animals (
    animal_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    animal_name     VARCHAR2(100 CHAR) NOT NULL,
    scientific_name VARCHAR2(150 CHAR),
    description     VARCHAR2(1000 CHAR),

    CONSTRAINT pk_animals PRIMARY KEY (animal_id),

    CONSTRAINT uq_animals_animal_name UNIQUE (animal_name)
);

-- ---------------------------------------------------------------------------
-- 2. Table storing information on the landscape
-- ---------------------------------------------------------------------------

CREATE TABLE biomes (
    biome_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    biome_name  VARCHAR2(100 CHAR) NOT NULL,
    description VARCHAR2(1000 CHAR),
    geom        MDSYS.SDO_GEOMETRY NOT NULL,

    CONSTRAINT pk_biomes PRIMARY KEY (biome_id),
    CONSTRAINT uq_biomes_name UNIQUE (biome_name)
);

-- ---------------------------------------------------------------------------
-- 3. Habitat polygons
-- A habitat is associated with one animal species
-- ---------------------------------------------------------------------------
CREATE TABLE habitats (
    habitat_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    habitat_name VARCHAR2(150 CHAR) NOT NULL,
    animal_id    NUMBER NOT NULL,
    biome_id     NUMBER NOT NULL,
    geom         MDSYS.SDO_GEOMETRY NOT NULL,
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_habitats PRIMARY KEY (habitat_id),

    CONSTRAINT fk_habitats_animal
    FOREIGN KEY (animal_id)
    REFERENCES animals (animal_id),

    CONSTRAINT fk_habitats_biome
    FOREIGN KEY (biome_id)
    REFERENCES biomes (biome_id)
);

-- ---------------------------------------------------------------------------
-- 4. Animal sightings, represented as points.
-- ---------------------------------------------------------------------------
CREATE TABLE sightings (
    sighting_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    animal_id        NUMBER NOT NULL,
    sighted_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    notes            VARCHAR2(1000 CHAR),
    geom             MDSYS.SDO_GEOMETRY NOT NULL,

    CONSTRAINT pk_sightings PRIMARY KEY (sighting_id),

    CONSTRAINT fk_sightings_animal
        FOREIGN KEY (animal_id)
        REFERENCES animals (animal_id)
);

-- ---------------------------------------------------------------------------
-- 5. Table storing Sighting images and properties
-- ---------------------------------------------------------------------------
CREATE TABLE sighting_images (
    sighting_id NUMBER NOT NULL,
    image       ORDSYS.ORDImage,
    image_si    ORDSYS.SI_StillImage,
    image_ac    ORDSYS.SI_AverageColor,
    image_ch    ORDSYS.SI_ColorHistogram,
    image_pc    ORDSYS.SI_PositionalColor,
    image_tx    ORDSYS.SI_Texture,

    CONSTRAINT pk_sighting_images
    PRIMARY KEY (sighting_id),

    CONSTRAINT fk_sighting_images_sighting
    FOREIGN KEY (sighting_id)
    REFERENCES sightings (sighting_id)
);

-- ---------------------------------------------------------------------------
-- 6. Table storing information trails through the map
-- ---------------------------------------------------------------------------
CREATE TABLE wildlife_trails (
    trail_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    trail_name  VARCHAR2(150 CHAR) NOT NULL,
    description VARCHAR2(1000 CHAR),
    geom        MDSYS.SDO_GEOMETRY NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_wildlife_trails PRIMARY KEY (trail_id)
);

-- ---------------------------------------------------------------------------
-- 7. Table storing information on the location of buildings for viewing animals
-- ---------------------------------------------------------------------------
CREATE TABLE checkpoints (
    checkpoint_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    checkpoint_name VARCHAR2(150 CHAR) NOT NULL,
    checkpoint_type VARCHAR2(50 CHAR),
    description     VARCHAR2(1000 CHAR),
    geom            MDSYS.SDO_GEOMETRY NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_checkpoints PRIMARY KEY (checkpoint_id)
);
-- ---------------------------------------------------------------------------
-- 8. Ordinary indexes on foreign keys and the sighting timestamp.
-- ---------------------------------------------------------------------------
CREATE INDEX idx_habitats_animal_id
    ON habitats (animal_id);

CREATE INDEX idx_sightings_animal_id
    ON sightings (animal_id);

CREATE INDEX idx_sightings_sighted_at
    ON sightings (sighted_at);

CREATE INDEX idx_habitats_biome_id
    ON habitats (biome_id);

