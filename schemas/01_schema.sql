-- =============================================================================
-- 01_schema.sql
-- Animal Habitats and Sightings Management System
-- Target: Oracle Database 19c/21c/23c with Oracle Spatial available.
--
-- Design notes:
--   * ANIMALS is a supporting lookup/entity table required by the Animal_Name
--     foreign keys.
--   * Surrogate ANIMAL_ID keys avoid using mutable names as foreign keys;
--     ANIMAL_NAME is still UNIQUE for lookup and display.
--   * WGS 84 / EPSG:4326 is used for longitude/latitude geometries.
--   * Geometry metadata is registered BEFORE spatial indexes are created.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Supporting animal table
-- ---------------------------------------------------------------------------
CREATE TABLE animals (
    animal_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    animal_name     VARCHAR2(100 CHAR) NOT NULL,
    scientific_name VARCHAR2(150 CHAR),
    description     VARCHAR2(1000 CHAR),
    CONSTRAINT pk_animals PRIMARY KEY (animal_id),
    CONSTRAINT uq_animals_animal_name UNIQUE (animal_name)
);

-- ---------------------------------------------------------------------------
-- 2. Habitat polygons
-- A habitat is associated with one animal species
-- ---------------------------------------------------------------------------
CREATE TABLE habitats (
    habitat_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    habitat_name VARCHAR2(150 CHAR) NOT NULL,
    animal_id    NUMBER NOT NULL,
    geom         MDSYS.SDO_GEOMETRY NOT NULL,
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_habitats PRIMARY KEY (habitat_id),
    CONSTRAINT fk_habitats_animal
        FOREIGN KEY (animal_id)
        REFERENCES animals (animal_id)
);

-- ---------------------------------------------------------------------------
-- 3. Animal sightings, represented as points.
-- The photograph is stored as a BLOB
-- that sightings can be inserted before a photograph is uploaded.
-- ---------------------------------------------------------------------------
CREATE TABLE sightings (
    sighting_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    animal_id        NUMBER NOT NULL,
    sighted_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    notes            VARCHAR2(1000 CHAR),
    image_data       BLOB,
    image_file_name  VARCHAR2(255 CHAR),
    image_mime_type  VARCHAR2(100 CHAR),
    geom             MDSYS.SDO_GEOMETRY NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_sightings PRIMARY KEY (sighting_id),
    CONSTRAINT fk_sightings_animal
        FOREIGN KEY (animal_id)
        REFERENCES animals (animal_id),
    CONSTRAINT ck_sightings_image_mime
        CHECK (
            image_mime_type IS NULL OR
            image_mime_type IN (
                'image/jpeg',
                'image/png',
                'image/webp',
                'image/gif'
            )
        )
);

-- ---------------------------------------------------------------------------
-- 4. Ordinary indexes on foreign keys and the sighting timestamp.
-- ---------------------------------------------------------------------------
CREATE INDEX idx_habitats_animal_id
    ON habitats (animal_id);

CREATE INDEX idx_sightings_animal_id
    ON sightings (animal_id);

CREATE INDEX idx_sightings_sighted_at
    ON sightings (sighted_at);

-- ---------------------------------------------------------------------------
-- 5. Spatial data informs Oracle on how to handle spatial data
-- For geodetic data, tolerance is measured in metres 0.05 m
-- ---------------------------------------------------------------------------
INSERT INTO user_sdo_geom_metadata
    (table_name, column_name, diminfo, srid)
VALUES (
    'HABITATS',
    'GEOM',
    SDO_DIM_ARRAY(
        SDO_DIM_ELEMENT('LONGITUDE', -180, 180, 0.05),
        SDO_DIM_ELEMENT('LATITUDE',   -90,  90, 0.05)
    ),
    4326
);

INSERT INTO user_sdo_geom_metadata
    (table_name, column_name, diminfo, srid)
VALUES (
    'SIGHTINGS',
    'GEOM',
    SDO_DIM_ARRAY(
        SDO_DIM_ELEMENT('LONGITUDE', -180, 180, 0.05),
        SDO_DIM_ELEMENT('LATITUDE',   -90,  90, 0.05)
    ),
    4326
);

COMMIT;

-- ---------------------------------------------------------------------------
-- 6. R-tree spatial indexes
-- ---------------------------------------------------------------------------
CREATE INDEX idx_habitats_geom
    ON habitats (geom)
    INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

CREATE INDEX idx_sightings_geom
    ON sightings (geom)
    INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

-- ---------------------------------------------------------------------------
-- 7. Verification: metadata should show two GEOM layers
-- ---------------------------------------------------------------------------
SELECT table_name, column_name, srid, diminfo
FROM user_sdo_geom_metadata
WHERE table_name IN ('HABITATS', 'SIGHTINGS')
ORDER BY table_name;

-- Verify index status and domain-index operation status.
SELECT index_name, table_name, index_type, status, domidx_status, domidx_opstatus
FROM user_indexes
WHERE index_name IN (
    'IDX_HABITATS_GEOM',
    'IDX_SIGHTINGS_GEOM',
    'IDX_HABITATS_ANIMAL_ID',
    'IDX_SIGHTINGS_ANIMAL_ID',
    'IDX_SIGHTINGS_SIGHTED_AT'
)
ORDER BY index_name;

-- =============================================================================
-- 8. Triggers
-- =============================================================================

CREATE OR REPLACE TRIGGER trg_habitats_validate_geom
BEFORE INSERT OR UPDATE OF geom ON habitats
    FOR EACH ROW
DECLARE
v_result VARCHAR2(2000);
BEGIN
    IF :NEW.geom IS NULL THEN
        RAISE_APPLICATION_ERROR(-20011, 'Habitat geometry cannot be NULL.');
END IF;

    IF :NEW.geom.SDO_GTYPE <> 2003 THEN
        RAISE_APPLICATION_ERROR(-20012, 'Habitat geometry must be a 2D polygon (SDO_GTYPE 2003).');
END IF;

    IF :NEW.geom.SDO_SRID <> 4326 THEN
        RAISE_APPLICATION_ERROR(-20013, 'Habitat geometry must use SRID 4326.');
END IF;

    v_result := SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(:NEW.geom, 0.05);

    IF v_result <> 'TRUE' THEN
        RAISE_APPLICATION_ERROR(-20014, 'Invalid habitat geometry: ' || v_result);
END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_sightings_validate_geom
BEFORE INSERT OR UPDATE OF geom ON sightings
    FOR EACH ROW
DECLARE
v_result VARCHAR2(2000);
BEGIN
    IF :NEW.geom IS NULL THEN
        RAISE_APPLICATION_ERROR(-20021, 'Sighting geometry cannot be NULL.');
END IF;

    IF :NEW.geom.SDO_GTYPE <> 2001 THEN
        RAISE_APPLICATION_ERROR(-20022, 'Sighting geometry must be a 2D point (SDO_GTYPE 2001).');
END IF;

    IF :NEW.geom.SDO_SRID <> 4326 THEN
        RAISE_APPLICATION_ERROR(-20023, 'Sighting geometry must use SRID 4326.');
END IF;

    v_result := SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(:NEW.geom, 0.05);

    IF v_result <> 'TRUE' THEN
        RAISE_APPLICATION_ERROR(-20024, 'Invalid sighting geometry: ' || v_result);
END IF;
END;
/

-- Confirm that the triggers are valid after creation.
SELECT trigger_name, status, table_name
FROM user_triggers
WHERE trigger_name IN ('TRG_HABITATS_VALIDATE_GEOM', 'TRG_SIGHTINGS_VALIDATE_GEOM')
ORDER BY trigger_name;
